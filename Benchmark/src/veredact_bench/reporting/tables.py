"""Paper tables from results/<experiment>/<method>/<tier>/ -> Overleaf/tables/<name>.tex (booktabs, never hand-edited).

tab_primitives.tex    tab:primitives  median (95% CI) of every primitive, VeRedact-PQ then the baselines
Only the manuscript's tables are written (author decision 2026-10-04).
"""

import re

from veredact_bench.reporting import style
from veredact_bench.reporting.load import metrics
from veredact_bench.utils.config import TABLE_DIR

OUT = TABLE_DIR
ORDER = list(style.PAPER_METHODS)


def sym_tex(symbol: str) -> str:
    """T_PA^c -> $T_{PA}^{c}$"""
    m = re.fullmatch(r"T_([A-Za-z]+)(?:\^(\w+))?", symbol)
    if not m:
        return symbol
    return f"$T_{{{m.group(1)}}}" + (f"^{{{m.group(2)}}}" if m.group(2) else "") + "$"


def tex_escape(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def _write(name: str, body: list[str], written: list):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text("% generated by scripts/make_tables.py — do not edit\n" + "\n".join(body) + "\n")
    written.append(f"Overleaf/tables/{name}.tex")


def table_primitives(tier, written):
    ms = metrics("exp00_primitives", tier)
    if not ms:
        return
    body = [r"\begin{tabular}{llr}", r"\toprule", r"Operation & Instantiation & Time (ms) \\", r"\midrule"]
    for key in [k for k in ORDER if k in ms]:
        body.append(rf"\multicolumn{{3}}{{l}}{{\textit{{{style.label(key)}}}}} \\")
        for k, v in ms[key]["points"].items():
            sym = k.split("|")[0].split("=", 1)[1]
            body.append(
                f"{sym_tex(sym)} & {tex_escape(v['instantiation'])} & "
                f"{v['median']:.3f} $\\pm$ {v['ci95_halfwidth']:.3f} \\\\"
            )
    body += [r"\bottomrule", r"\end{tabular}"]
    _write("tab_primitives", body, written)


def make_all(tier: str) -> list[str]:
    written: list[str] = []
    for t in (table_primitives,):
        t(tier, written)
    return written
